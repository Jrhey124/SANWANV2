const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const Database=require('better-sqlite3-multiple-ciphers');
const {composeArgs,selectedDocker,detectWorker,repairConfigPermissions,servicePath,inspectService,registerService}=require('./setup-deployments');
const {processDeploymentCandidates,recordManualStaging}=require('./dist/deployment-candidates');
const {monitoringRegistry}=require('./dist/service-registry');

module.exports=async function(temp){
  const fixture=path.join(temp,'cicd-app');fs.cpSync(path.join(__dirname,'templates/cicd-app'),fixture,{recursive:true});
  for(const mode of [{id:'healthy',unhealthy:false,failTests:false},{id:'unhealthy',unhealthy:true,failTests:false},{id:'failing-ci',unhealthy:false,failTests:true}]){
    fs.writeFileSync(path.join(fixture,'release.json'),JSON.stringify(mode));
    const tested=spawnSync(process.execPath,['--test','server.test.js'],{cwd:fixture,encoding:'utf8'});
    assert.equal(tested.status,mode.failTests?1:0,tested.stderr||tested.stdout);
  }
  assert.deepEqual(composeArgs({}),['compose','-f','docker-compose.yml']);
  assert.deepEqual(composeArgs({DEPLOYMENTS_ENABLED:'true'}),['compose','-f','docker-compose.yml','-f','docker-compose.worker.yml','--profile','deployment']);
  const dockerRun=(rootless)=> (_command,args)=>({status:0,stdout:args.includes('info')?JSON.stringify(rootless?['name=rootless']:[]):args.includes('show')?'rootless':JSON.stringify([{Endpoints:{docker:{Host:'unix:///run/user/1000/docker.sock'}}}])});
  const selected=selectedDocker('docker',{run:dockerRun(true),env:{},platform:'linux',stat:()=>({uid:1000,gid:1000}),uid:1000,gid:1000});
  assert.equal(selected.rootless,true);assert.equal(selected.socket,'/run/user/1000/docker.sock');assert.equal(selected.gid,'0','daemon owner maps to root inside the rootless container');
  assert.equal(selectedDocker('docker',{run:dockerRun(false),env:{},platform:'linux'}).rootless,false);
  assert.equal(selectedDocker('docker',{run:dockerRun(true),env:{},platform:'win32'}).rootless,false);
  assert.equal(detectWorker('docker',{run:(_c,args)=>({status:0,stdout:args[0]==='inspect'?'dedicated-project':'container'})}),true);
  assert.equal(detectWorker('docker',{run:()=>({status:1})}),undefined,'unavailable Docker must not be mistaken for a disabled legacy worker');
  assert.equal(detectWorker('docker',{run:()=>({status:0,stdout:''})}),false);

  const root=path.join(temp,'guided-setup');fs.mkdirSync(root);
  fs.writeFileSync(path.join(root,'.env'),'SQLITE_KEY=keep-key\nWORKER_TOKEN=keep-token\n',{mode:0o600});
  repairConfigPermissions(root);
  const registry=path.join(root,'config/services.json');
  fs.writeFileSync(registry,'{"services":{}}');
  if(process.platform!=='win32')fs.chmodSync(registry,0o600);
  repairConfigPermissions(root);
  assert.equal(fs.readFileSync(path.join(root,'.env'),'utf8'),'SQLITE_KEY=keep-key\nWORKER_TOKEN=keep-token\n');
  if(process.platform!=='win32'){
    assert.equal(fs.statSync(registry).mode&0o777,0o644);
    assert.equal(fs.statSync(path.join(root,'.env')).mode&0o777,0o600);
    assert.equal(fs.statSync(path.join(root,'config')).mode&0o555,0o555);
  }
  const log=[];
  const answers=['demo','','','','','','','','',''];
  const healthyRun=(_c,args)=>({status:0,stdout:args.includes('config')?JSON.stringify({services:{app:{image:'ghcr.io/owner/test:latest',healthcheck:{test:['CMD','true']}}}}):JSON.stringify({Test:['CMD','true']})});
  await registerService({GITHUB_REPOSITORIES:'owner/test'},'docker',{prompt:async()=>answers.shift()??'',choice:async()=> '1',print:x=>log.push(x)},{cwd:root,run:healthyRun});
  let entry=JSON.parse(fs.readFileSync(registry)).services.demo;
  assert.equal(entry.github_repository,'owner/test');
  assert.notEqual(entry.environments.staging.compose_project,entry.environments.production.compose_project);
  const staging=JSON.parse(fs.readFileSync(path.join(root,'services',entry.environments.staging.compose_file)));
  const production=JSON.parse(fs.readFileSync(path.join(root,'services',entry.environments.production.compose_file)));
  assert.notEqual(staging.services.app.ports[0],production.services.app.ports[0]);
  assert.match(log.join('\n'),/preview/);assert.match(log.join('\n'),/PASS/);
  const before=fs.readFileSync(registry,'utf8');
  await registerService({},'docker',{prompt:async()=> 'demo',choice:async()=> '1',print:()=>{}},{cwd:root,run:healthyRun});
  assert.equal(fs.readFileSync(registry,'utf8'),before,'Keep preserves existing service');
  const replacementAnswers=['demo','','Updated workflow','','','','','','',''];
  const choices=['2','2','1'];
  await registerService({GITHUB_REPOSITORIES:'owner/test'},'docker',{prompt:async()=>replacementAnswers.shift()??'',choice:async()=>choices.shift()??'1',print:()=>{}},{cwd:root,run:healthyRun});
  entry=JSON.parse(fs.readFileSync(registry)).services.demo;
  assert.equal(entry.workflow_name,'Updated workflow');
  assert.throws(()=>servicePath('../outside.yml',root),/relative Compose/);
  assert.equal(inspectService('docker','fixture','app',{run:(_c,args)=>args.includes('config')?{status:0,stdout:'{"services":{"app":{"image":"example/test"}}}'}:{status:1,stdout:''}}),false,'missing image health is not readiness');
  assert.throws(()=>inspectService('docker','fixture','app',{run:()=>({status:0,stdout:'{"services":{"app":{"image":"example/test","healthcheck":{"disable":true}}}}'})}),/disabled/);
  let warned=false;fs.writeFileSync(registry,'{"services":{"bad":{}}}');
  assert.deepEqual(monitoringRegistry(registry,()=>{warned=true;}),{services:{}});assert.equal(warned,true);

  const dbFile=path.join(temp,'candidate-state.sqlite');
  let db=new Database(dbFile);
  db.exec("CREATE TABLE staging_deployment(service TEXT,sha TEXT,status TEXT,detail TEXT,attempts INTEGER,updated_at TEXT,PRIMARY KEY(service,sha)); CREATE TABLE pending_deployment(id INTEGER PRIMARY KEY,service TEXT,environment TEXT,operation TEXT,status TEXT,sha TEXT);");
  const service={github_repository:'owner/test',workflow_name:'Publish',staging_branch:'develop',production_branch:'main'};
  const run=(n,branch='develop')=>({id:n,run_number:n,name:'Publish',head_sha:String(n).repeat(40).slice(0,40),head_branch:branch,status:'completed',conclusion:'success',event:'push',head_repository:{full_name:'owner/test'}});
  const calls=[],notices=[];let failures=false;
  const worker=async body=>{calls.push(body);if(failures)throw Error('health failure');return {digest:'pinned',active_sha:body.sha};};
  const poll=(runs,baseline=true,prior=new Set(),enabled=true,verify=async()=>{})=>processDeploymentCandidates(db,{demo:service},runs,baseline,prior,enabled,worker,verify,async n=>notices.push(n));
  await poll([run(2),run(1)],false);await poll([run(1),run(2)],true,new Set([1,2]));assert.equal(calls.length,0,'baseline does not deploy');
  await poll([run(3),run(2)]);assert.equal(calls.length,1);assert.equal(calls[0].sha,run(3).head_sha);
  await poll([run(2),run(3)]);assert.equal(calls.length,1,'repeated polls do not deploy twice');
  await poll([run(5),run(4)]);assert.equal(calls.at(-1).sha,run(5).head_sha);assert.equal(calls.length,2,'only newest successful matching run deploys');
  db.close();db=new Database(dbFile);
  await poll([run(4)]);assert.equal(calls.length,2,'restart and stale responses cannot regress');
  failures=true;for(let i=0;i<4;i++)await poll([run(6)]);assert.equal(calls.length,5,'failed releases retry at most three times');assert.equal(notices.filter(n=>n.kind==='failed').length,3);
  failures=false;
  await poll([run(7)],true,new Set(),false);assert.equal(calls.length,5,'disabled worker is not called');
  db.prepare("INSERT INTO staging_deployment VALUES('demo',?,'deploying','crash recovery',3,'now')").run(run(7).head_sha);
  const recovered=async body=>{assert.equal(body.operation,'status');return {active_sha:run(7).head_sha};};
  await processDeploymentCandidates(db,{demo:service},[run(7)],true,new Set([7]),true,recovered,async()=>{},async()=>{});
  assert.equal(db.prepare('SELECT status FROM staging_deployment WHERE sha=?').get(run(7).head_sha).status,'healthy','restart reconciles worker state even at retry ceiling');
  db.prepare("INSERT INTO pending_deployment VALUES(1,'demo','production','release','pending',?)").run(run(8).head_sha);
  await poll([run(8,'main')],false);
  await poll([run(9,'main'),run(8,'main')],true,new Set(),true,async(_s,sha)=>assert.equal(sha,run(9).head_sha));
  assert.equal(db.prepare('SELECT status FROM pending_deployment WHERE id=1').get().status,'superseded');
  db.prepare("INSERT INTO pending_deployment VALUES(2,'demo','production','release','pending',?)").run(run(10).head_sha);
  await poll([run(8,'main')]);assert.equal(db.prepare('SELECT status FROM pending_deployment WHERE id=2').get().status,'pending');
  await poll([run(11,'main')],true,new Set(),true,async()=>{throw Error('stale release');});
  assert.equal(db.prepare('SELECT status FROM pending_deployment WHERE id=2').get().status,'pending','unverified poll result cannot supersede an approval');
  await processDeploymentCandidates(db,monitoringRegistry(registry,()=>{}).services,[run(12)],true,new Set(),true,worker,async()=>{},async()=>{});
  assert.equal(calls.length,5,'broken registry leaves monitoring usable without deployment calls');
  db.prepare("INSERT INTO staging_deployment VALUES('legacy',?,'deploying','interrupted before upgrade',3,'now')").run(run(30).head_sha);
  await processDeploymentCandidates(db,{legacy:service},[run(30)],true,new Set([30]),true,async body=>{assert.equal(body.operation,'status');return {active_sha:run(30).head_sha};},async()=>{},async()=>{});
  assert.equal(db.prepare("SELECT status FROM staging_deployment WHERE service='legacy'").get().status,'healthy','legacy attempts are recovered when introducing release cursors');
  recordManualStaging(db,'demo',service,run(20).head_sha,20);
  await poll([run(19)]);assert.equal(calls.length,5,'manual newer staging release prevents older automatic deployment');
  const changedService={...service,workflow_name:'New publish'};
  await processDeploymentCandidates(db,{demo:changedService},[{...run(1),name:'New publish'}],true,new Set(),true,worker,async()=>{},async()=>{});
  assert.equal(calls.length,6,'changing the configured workflow resets its release ordering scope');
  db.close();
  console.log('PASS: guided deployment setup, permission repair, rootless selection, persistent release ordering, retry/recovery and approval supersession.');
};

const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const Database=require('better-sqlite3-multiple-ciphers');
const {runDiagnostics}=require('./dist/diagnostics.js');
const {runSavedChecks}=require('./setup-checks.js');

module.exports=async temp=>{
  const key='private-key-'.repeat(8);
  const dbPath=path.join(temp,'sanwan.db');
  const db=new Database(dbPath);db.pragma("cipher = 'sqlcipher'");db.key(Buffer.from(key));
  db.exec("CREATE TABLE setting(key TEXT,value TEXT); INSERT INTO setting VALUES('ask_model','saved-model')");db.close();
  const servicesPath=path.join(temp,'services.json');fs.writeFileSync(servicesPath,JSON.stringify({services:{}}));
  const before=fs.readFileSync(dbPath);
  const registryBefore=fs.readFileSync(servicesPath);
  const env={DISCORD_TOKEN:'private-token-value',DISCORD_GUILD_ID:'guild',DISCORD_APPLICATION_ID:'app',GITHUB_CHANNEL_ID:'channel',GITHUB_TOKEN:'private-github-value',GITHUB_REPOSITORIES:'acme/app',ASK_PROVIDER:'openai-compatible',ASK_BASE_URL:'https://ai.example/v1',ASK_MODEL:'wrong-env-model',ASK_API_KEY:'private-ai-value',SQLITE_KEY:key,DATA_DIR:temp,SERVICES_CONFIG:servicesPath,WORKER_URL:'http://worker:8877'};
  const requests=[];
  const request=async(url,options)=>{
    requests.push({url,options});assert.equal(options.method,undefined,'diagnostics only use GET');assert.ok(options.signal);
    let data={};
    if(url.endsWith('/users/@me'))data={id:'bot',bot:true};
    else if(url.endsWith('/commands'))data=['help','ping','ci','deploy','task','note','schedule','logs','errors','status','ask'].map(name=>({name}));
    else if(url.includes('/channels/'))data={guild_id:'guild',type:0,permission_overwrites:[]};
    else if(url.endsWith('/roles'))data=[{id:'guild',permissions:'3072'}];
    else if(url.endsWith('/members/bot'))data={roles:[]};
    else if(url.includes('/actions/runs'))data={workflow_runs:[]};
    else if(url.includes('/events'))data=[];
    else if(url.endsWith('/models'))data={data:[{id:'saved-model'}]};
    else if(url.endsWith('/health'))data={ok:true};
    return new Response(JSON.stringify(data),{status:200});
  };
  const rows=await runDiagnostics(env,request,true);
  assert.equal(rows.find(r=>r.name==='AI model access').status,'PASS','saved /ask switch model must override env');
  assert.equal(rows.find(r=>r.name==='GITHUB_CHANNEL_ID').status,'PASS');
  assert.equal(rows.find(r=>r.name==='Slash commands').status,'PASS');
  assert.equal(rows.find(r=>r.name==='Service registry').status,'WARN');
  assert.equal(rows.filter(r=>r.name.startsWith('GitHub acme/app')).length,3);
  assert.ok(rows.filter(r=>r.name.startsWith('GitHub acme/app')).every(r=>r.status==='PASS'),'empty feeds still prove access');
  assert.ok(rows.some(r=>r.status==='SKIP'));
  assert.deepEqual(fs.readFileSync(dbPath),before,'active encrypted model lookup is read-only');
  assert.deepEqual(fs.readFileSync(servicesPath),registryBefore);
  const denied=await runDiagnostics(env,async()=>new Response('{}',{status:403}),false,()=>env.ASK_MODEL);
  assert.ok(denied.some(r=>r.detail.includes('HTTP 403')));
  assert.ok(denied.some(r=>r.name==='AI model access'),'one failure must not stop remaining checks');
  const timeout=await runDiagnostics(env,async()=>{throw new Error(env.ASK_API_KEY);},false,()=>env.ASK_MODEL);
  assert.ok(timeout.some(r=>r.detail.includes('timed out')));
  const missingModel=await runDiagnostics(env,request,false,()=>env.ASK_MODEL);
  assert.equal(missingModel.find(r=>r.name==='AI model access').status,'FAIL');
  const noFeatures=await runDiagnostics({},request);
  assert.equal(noFeatures.find(r=>r.name==='GitHub').status,'SKIP');
  assert.equal(noFeatures.find(r=>r.name==='AI').status,'SKIP');
  const noPermission=await runDiagnostics(env,async(url,options)=>url.includes('/roles')?new Response(JSON.stringify([{id:'guild',permissions:'1024'}])):request(url,options),false,()=>env.ASK_MODEL);
  assert.equal(noPermission.find(r=>r.name==='GITHUB_CHANNEL_ID').status,'FAIL');
  const rendered=JSON.stringify([rows,denied,timeout,missingModel,noFeatures,noPermission]);
  for(const secret of [env.DISCORD_TOKEN,env.GITHUB_TOKEN,env.ASK_API_KEY,key])assert.ok(!rendered.includes(secret));
  const output=[];
  await runSavedChecks({run:()=>({status:1,stderr:'private-token-value'}),print:x=>output.push(x)});
  assert.match(output.join('\n'),/Engine unavailable/);assert.doesNotMatch(output.join('\n'),/private-token-value/);
  let time=0;
  const mockRun=(command,args,options)=>{
    assert.ok(options.timeout);
    if(args[0]==='version')return {status:0,stdout:'1'};
    if(args.includes('ps')&&args.includes('-q'))return {status:0,stdout:'container'};
    if(args.includes('{{json .State}}'))return {status:0,stdout:JSON.stringify({Running:true,Health:{Status:'starting'}})};
    if(args[0]==='inspect')return {status:0,stdout:'project'};
    if(args[0]==='ps')return {status:0,stdout:''};
    assert.ok(args.includes('dist/diagnostics.js'));
    return {status:0,stdout:JSON.stringify([{status:'PASS',name:'Fixture',detail:'Checks ran.'}])};
  };
  await runSavedChecks({run:mockRun,now:()=>time,sleep:async ms=>{time+=ms;},print:x=>output.push(x)});
  assert.equal(time,60000,'startup waiting must stop at 60 seconds');
  assert.match(output.join('\n'),/Fixture: Checks ran/);
  const registeredPath=path.join(temp,'registered-services.json');
  fs.writeFileSync(registeredPath,JSON.stringify({services:{demo:{github_repository:'acme/app',workflow_name:'Publish',staging_branch:'develop',production_branch:'main',image_repository:'ghcr.io/acme/app',environments:{staging:{compose_file:'demo/staging.json',compose_project:'demo-staging',compose_service:'app'},production:{compose_file:'demo/production.json',compose_project:'demo-production',compose_service:'app'}}}}}));
  const registeredEnv={...env,SERVICES_CONFIG:registeredPath,DEPLOYMENTS_ENABLED:'true',WORKER_TOKEN:'private-worker-value',GHCR_USERNAME:'acme',GHCR_TOKEN:'private-package-value'};
  const simulations=[];
  const readinessRequest=async(url,options)=>{
    if(url.includes('ghcr.io/token'))return new Response(JSON.stringify({token:'ephemeral-private-value'}));
    if(url.includes('/tags/list'))return new Response(JSON.stringify({tags:[]}));
    if(url.endsWith('/v1/action')){
      const body=JSON.parse(options.body);assert.equal(body.operation,'simulate');assert.equal(options.method,'POST');assert.ok(options.signal);
      assert.equal(options.headers.Authorization,'Bearer '+registeredEnv.WORKER_TOKEN);simulations.push(body);
      return new Response(JSON.stringify({ok:true,changed:false}));
    }
    return request(url,options);
  };
  const ready=await runDiagnostics(registeredEnv,readinessRequest,false,()=>env.ASK_MODEL);
  assert.equal(ready.find(r=>r.name==='GHCR ghcr.io/acme/app').status,'PASS','empty registry metadata is accessible');
  assert.equal(ready.filter(r=>r.name.startsWith('Service demo/')&&r.status==='PASS').length,2);
  assert.deepEqual(simulations.map(s=>s.environment),['staging','production']);
  const unhealthy=await runDiagnostics(registeredEnv,async(url,options)=>url.endsWith('/v1/action')&&JSON.parse(options.body).environment==='staging'?new Response('{}',{status:400}):readinessRequest(url,options),false,()=>env.ASK_MODEL);
  assert.equal(unhealthy.find(r=>r.name==='Service demo/staging').status,'FAIL');
  assert.equal(unhealthy.find(r=>r.name==='Service demo/production').status,'PASS','one service failure does not stop other checks');
  for(const secret of [registeredEnv.WORKER_TOKEN,registeredEnv.GHCR_TOKEN,'ephemeral-private-value'])assert.ok(!JSON.stringify([ready,unhealthy]).includes(secret));
  console.log('PASS: setup diagnostics check optional integrations, respect bounds, report failures safely, and preserve saved data.');
};

const assert = require('node:assert/strict');
const Database = require('better-sqlite3-multiple-ciphers');
const path = require('node:path');
const { initializeActivityStorage, pollRepositoryActivity, activityMessage, activityPollLabel } = require('./dist/github-activity.js');

module.exports = async function testGitHubActivity(temp) {
  const file = path.join(temp, 'activity.db');
  let db = new Database(file);
  initializeActivityStorage(db);
  let time = 0;
  let calls = 0;
  let pages = [[]];
  let status = 200;
  let interval = 60;
  const request = async (url, options) => {
    calls++;
    assert.equal(options.headers.Authorization, 'Bearer test-token');
    assert.match(url, /^https:\/\/api.github.com\/repos\/acme\/app2?\/events\?/i);
    const page = Number(new URL(url).searchParams.get('page'));
    return new Response(JSON.stringify(pages[page-1] ?? []), {status,headers:{'X-Poll-Interval':String(interval)}});
  };
  const delivered = [];
  const notify = async message => { delivered.push(message); return true; };
  const poll = (repo='acme/app', send=notify) => {
    time += 120000;
    return pollRepositoryActivity(db,repo,'test-token',send,request,()=>time);
  };
  const push = id => ({id,type:'PushEvent',actor:{login:'dev'},payload:{ref:'refs/heads/main',head:'a'.repeat(40)}});
  const branch = (id,type) => ({id,type,actor:{login:'dev'},payload:{ref_type:'branch',ref:'feature/test'}});
  try {
    pages = [[push('1')]];
    const initial = await poll();
    assert.equal(initial.status,'baseline');
    assert.match(activityPollLabel(initial),/baseline saved/);
    assert.equal(delivered.length,0,'first poll must baseline history silently');
    pages = [[branch('4','DeleteEvent'),push('3'),branch('2','CreateEvent'),push('1')]];
    const checked = await poll();
    assert.equal(checked.status,'checked');
    assert.match(activityPollLabel(checked),/Checked for new pushes/);
    assert.equal(delivered.length,3);
    assert.match(delivered[0],/branch created.*feature\/test/);
    assert.match(delivered[1],/GitHub push.*dev pushed.*main.*aaaaaaa/);
    assert.match(delivered[2],/branch deleted/);
    await poll();
    assert.equal(delivered.length,3,'repeated polling must not duplicate notifications');
    db.close(); db = new Database(file); initializeActivityStorage(db);
    await poll('ACME/APP');
    assert.equal(delivered.length,3,'restart and repository casing must preserve deduplication');
    pages[0].unshift(branch('5','CreateEvent'));
    await poll('acme/app',async()=>false);
    assert.equal(delivered.length,3);
    await poll();
    assert.equal(delivered.length,4,'failed notification must be retried');
    pages = [Array.from({length:100},(_,i)=>({id:`ignored-${i}`,type:'WatchEvent'})),[branch('6','CreateEvent')]];
    const before = calls;
    await poll();
    assert.equal(calls-before,2,'events on the second page must be fetched');
    assert.equal(delivered.length,5);
    interval = 180;
    await poll();
    const throttled = calls;
    const waiting = await pollRepositoryActivity(db,'acme/app','test-token',notify,request,()=>time+60000);
    assert.equal(waiting.status,'waiting');
    assert.match(activityPollLabel(waiting),/try again/);
    assert.equal(calls,throttled,'GitHub polling interval must be honored');
    let finishConcurrent;
    const slowRequest = () => new Promise(resolve => { finishConcurrent = () => resolve(new Response('[]',{status:200,headers:{'X-Poll-Interval':'60'}})); });
    const activePoll = pollRepositoryActivity(db,'acme/app','test-token',notify,slowRequest,()=>time+1000000);
    const concurrent = await pollRepositoryActivity(db,'ACME/APP','test-token',notify,request,()=>time+1000000);
    assert.equal(concurrent.status,'already-checking');
    assert.match(activityPollLabel(concurrent),/already in progress/);
    finishConcurrent();
    assert.equal((await activePoll).status,'checked');
    status = 403;
    await assert.rejects(poll('acme/app2'),/HTTP 403/);
    assert.equal(db.prepare('SELECT * FROM github_activity_baseline WHERE repository=?').get('acme/app2'),undefined,'failed fetch must not establish a baseline');
    status = 200; time += 180000;
    await poll('acme/app2');
    assert.equal(delivered.length,5,'a new repository gets an independent silent baseline');
    assert.equal(activityMessage('acme/app',branch('7','WatchEvent')),undefined);
    assert.equal(activityMessage('acme/app',{id:'8',type:'CreateEvent',payload:{ref_type:'tag',ref:'v1'}}),undefined);
    assert.equal(activityMessage('acme/app',{...push('9'),payload:{ref:'refs/heads/main',head:'0'.repeat(40)}}),undefined);
    assert.doesNotMatch(delivered.join('\n'),/test-token/);
  } finally { db.close(); }
  console.log('PASS: GitHub activity polling reports pushes and branch changes, persists deduplication, retries delivery, paginates, and respects server intervals.');
};
